package ua.nichnyk.listen

import android.content.Context
import androidx.core.content.ContextCompat

/**
 * Контекст, у якого рядки беруться мовою застосунку, а не системи.
 *
 * Мову вибирають у налаштуваннях, і на API 33+ її тримає системний
 * `LocaleManager` — там будь-який контекст, зокрема контекст застосунку, віддає
 * рядки правильною мовою. На API 26–32 системного механізму немає, і
 * `AppCompatDelegate.setApplicationLocales` емулює його, перевдягаючи контексти
 * **активностей**. Контекст застосунку лишається на системній локалі.
 *
 * Через це кожен снекбар, зібраний у ViewModel чи в [ua.nichnyk.listen.playback.PlayerManager]
 * через `app.getString(...)`, показувався системною мовою, щойно вона розходилася
 * з обраною: український інтерфейс і англійське «File is missing or was moved».
 * Знайдено на емуляторі API 30 із системною `en-US` та українською в застосунку.
 *
 * `getContextForLanguage` розвʼязує обидва випадки однаково: на API 33+ віддає
 * контекст як є, нижче — загортає в конфігурацію з локалями AppCompat.
 *
 * Викликаємо на кожному зверненні, а не кешуємо: мову перемикають з екрана
 * налаштувань, і збережений контекст лишився б зі старою. Рядки тут — тексти
 * помилок і сповіщень, тобто не гарячий шлях.
 */
fun Context.forAppLocale(): Context = ContextCompat.getContextForLanguage(this)
